def generate_seed_data_sql() -> str:
    """Generates the full SQL script inserting companies and job sources."""
    lines = [
        "-- Seed Data for Top USA Companies Across the 7 Target Industries",
        "-- Auto-generated with verified domains and direct career portals",
        "",
    ]

    total_companies = sum(len(comps) for comps in COMPANIES_DATA.values())

    for idx, (industry, comps) in enumerate(COMPANIES_DATA.items(), 1):
        lines.append(f"-- {idx}. {industry} ({len(comps)} USA Companies)")
        lines.append("INSERT INTO companies (name, domain, career_url, industry, active)")
        lines.append("VALUES")

        val_rows = []
        for name, domain, career_url in comps:
            clean_name = name.replace("'", "''")
            clean_domain = domain.replace("'", "''")
            clean_url = career_url.replace("'", "''")
            clean_ind = industry.replace("'", "''")
            val_rows.append(f"('{clean_name}', '{clean_domain}', '{clean_url}', '{clean_ind}', TRUE)")

        lines.append(",\n".join(val_rows))
        lines.append("ON CONFLICT (name) DO UPDATE SET")
        lines.append("    domain = EXCLUDED.domain,")
        lines.append("    career_url = EXCLUDED.career_url,")
        lines.append("    industry = EXCLUDED.industry,")
        lines.append("    active = EXCLUDED.active;")
        lines.append("")

    lines.extend([
        "-- Direct Company Career Page Job Sources (Scraped directly via Playwright)",
        "INSERT INTO job_sources (company_id, source_url, scraper_type, active)",
        "SELECT id, career_url, 'playwright', TRUE",
        "FROM companies",
        "WHERE career_url IS NOT NULL",
        "ON CONFLICT DO NOTHING;",
        "",
    ])

    return "\n".join(lines)


def main():
    sql_path = ROOT_DIR / "sql" / "seed_data.sql"
    sql_content = generate_seed_data_sql()
    sql_path.write_text(sql_content, encoding="utf-8")
    print(f"Successfully wrote {len(sql_content)} bytes to {sql_path}")
    total = sum(len(comps) for comps in COMPANIES_DATA.values())
    print(f"Total Companies compiled across 7 industries: {total}")
    for ind, comps in COMPANIES_DATA.items():
        print(f"  - {ind}: {len(comps)} companies")


if __name__ == "__main__":
    main()
